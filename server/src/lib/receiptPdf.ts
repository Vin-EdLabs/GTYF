/**
 * PDF receipt: GTYF logo, the donor's name, the amount, a "PAID" stamp, the
 * details and a thank-you note, on a page with faint exercise-book lines.
 * Uses PDFKit's built-in Helvetica so it works on any server without font files.
 */
import { existsSync } from 'node:fs';
import PDFDocument from 'pdfkit';
import { fromServerRoot } from './paths';
import type { ReceiptWords } from './receiptText';
import type { Writable } from 'node:stream';
import { formatCedis as formatCedisSymbol, formatDate } from '@gtyf/shared';

// PDFKit's built-in fonts have no ₵ glyph, so PDFs use the ISO code: GHS 200.00.
const formatCedis = (pesewas: number, opts?: { decimals?: boolean }) => formatCedisSymbol(pesewas, opts).replace('GH₵', 'GHS');

export interface ReceiptPdfData {
  /** Editable wording (Admin → Website → Donation & thank-you text). */
  words: ReceiptWords;
  orgName: string;
  registrationNumber?: string;
  siteUrl: string;
  reference: string;
  donorName: string;
  firstName: string;
  paidAt: Date;
  causeName: string;
  amount: number;
  fee: number;
  total: number;
  monthly: boolean;
  channel: string | null;
  impact: string | null;
  dedication: { type: 'honour' | 'memory'; name: string } | null;
}

const INK = '#0B1422';
const SLATE = '#5B6676';
const RULE = '#E4EAF7';
const MARGIN = '#F1C7C4';
const GREEN = '#1F9D55';
const WARM = '#FFF6E0';
const WARM_TEXT = '#7A4F00';

// Generated by `npm run brand -w server`; the server runs from the server/ folder.
const LOGO = fromServerRoot('assets', 'logo-full.png');

const channelLabel = (c: string | null) =>
  c === 'mobile_money' ? 'Mobile Money' : c === 'card' ? 'Card' : c === 'bank' || c === 'bank_transfer' ? 'Bank' : 'Paystack';

export function writeReceiptPdf(out: Writable, d: ReceiptPdfData) {
  const doc = new PDFDocument({ size: 'A5', margin: 0, info: { Title: `Receipt ${d.reference}`, Author: d.orgName } });
  doc.pipe(out);
  const W = doc.page.width; // 419.5
  const H = doc.page.height; // 595.3
  const x = 40;
  const colW = W - x * 2;

  // Faint paper lines and margin, below the header band
  for (let y = 118; y < H - 10; y += 21) doc.moveTo(0, y).lineTo(W, y).lineWidth(0.5).strokeColor(RULE).stroke();
  doc.moveTo(26, 96).lineTo(26, H).lineWidth(0.8).strokeColor(MARGIN).stroke();

  // Header band
  doc.rect(0, 0, W, 96).fill('#FFFFFF');
  if (existsSync(LOGO)) doc.image(LOGO, x - 6, 16, { width: 64, height: 64 });
  doc.fillColor(INK).font('Helvetica-Bold').fontSize(14).text(d.orgName, x + 66, 32, { width: colW - 66 });
  doc.font('Helvetica').fontSize(9).fillColor(SLATE).text(d.words.title, x + 66, 52);
  doc.moveTo(0, 96).lineTo(W, 96).lineWidth(0.6).strokeColor('#E6E9EF').stroke();

  // PAID stamp
  doc.save();
  doc.rotate(-14, { origin: [W - 70, 150] });
  doc.circle(W - 70, 150, 34).lineWidth(2.2).strokeColor(GREEN).strokeOpacity(0.75).stroke();
  doc.fillColor(GREEN).fillOpacity(0.85).font('Helvetica-Bold').fontSize(14).text('PAID', W - 104, 140, { width: 68, align: 'center' });
  doc.fontSize(5.5).text('WITH THANKS', W - 104, 157, { width: 68, align: 'center', characterSpacing: 1 });
  doc.restore();
  doc.fillOpacity(1).strokeOpacity(1);

  // Donor + amount
  doc.font('Helvetica').fontSize(9).fillColor(SLATE).text(d.words.receivedFrom, x, 118);
  doc.font('Helvetica-Bold').fontSize(18).fillColor(INK).text(d.donorName, x, 132, { width: colW - 90 });
  let y = Math.max(doc.y + 10, 170);
  doc.font('Helvetica').fontSize(9).fillColor(SLATE).text(d.monthly ? 'Monthly gift' : 'Gift', x, y);
  doc.font('Helvetica-Bold').fontSize(30).fillColor(INK).text(`${formatCedis(d.amount, { decimals: true })}${d.monthly ? ' /month' : ''}`, x, y + 12);
  y = doc.y + 4;
  if (d.fee) {
    doc.font('Helvetica').fontSize(9).fillColor(SLATE).text(`Total paid ${formatCedis(d.total, { decimals: true })} (includes ${formatCedis(d.fee, { decimals: true })} fees covered)`, x, y);
    y = doc.y;
  }

  // Details
  y += 14;
  const rows: [string, string][] = [
    ['Receipt no.', d.reference],
    ['Date', formatDate(d.paidAt.toISOString())],
    ['Cause', d.causeName],
    ['Paid by', channelLabel(d.channel)],
  ];
  for (const [label, value] of rows) {
    doc.moveTo(x, y).lineTo(x + colW, y).dash(2, { space: 2 }).lineWidth(0.6).strokeColor('#C9CED8').stroke().undash();
    doc.font('Helvetica').fontSize(10).fillColor(SLATE).text(label, x, y + 7);
    doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text(value, x + 90, y + 7, { width: colW - 90, align: 'right' });
    y = Math.max(doc.y, y + 14) + 7;
  }
  doc.moveTo(x, y).lineTo(x + colW, y).dash(2, { space: 2 }).lineWidth(0.6).strokeColor('#C9CED8').stroke().undash();

  // Impact
  const impact = d.impact?.replace(/^.*?=\s*/, '');
  if (impact) {
    y += 14;
    doc.font('Helvetica-Bold').fontSize(12);
    const textH = doc.heightOfString(`${impact}${d.monthly ? ' every month' : ''}`, { width: colW - 28 });
    doc.roundedRect(x, y, colW, textH + 34, 10).fill(WARM);
    doc.font('Helvetica-Bold').fontSize(7.5).fillColor(WARM_TEXT).text('YOUR GIFT PROVIDES', x + 14, y + 10, { characterSpacing: 0.8 });
    doc.font('Helvetica-Bold').fontSize(12).fillColor(INK).text(`${impact}${d.monthly ? ' every month' : ''}`, x + 14, y + 22, { width: colW - 28 });
    y += textH + 34;
  }
  if (d.dedication) {
    y += 10;
    doc.font('Helvetica-Oblique').fontSize(10).fillColor(SLATE).text(`Given ${d.dedication.type === 'honour' ? 'in honour of' : 'in memory of'} ${d.dedication.name}.`, x, y, { width: colW });
    y = doc.y;
  }

  // Thank-you note
  y += 16;
  doc
    .font('Helvetica')
    .fontSize(10.5)
    .fillColor(INK)
    .text(d.words.thankYou, x, y, {
      width: colW,
      lineGap: 3,
    });
  doc.font('Helvetica-Bold').fontSize(11).text(d.words.signOff, x, doc.y + 8);

  doc
    .font('Helvetica')
    .fontSize(7.5)
    .fillColor(SLATE)
    .text(
      `Payments processed securely by Paystack.${d.registrationNumber ? `  Reg. No. ${d.registrationNumber}.` : ''}  ${d.siteUrl.replace(/^https?:\/\//, '')}`,
      x,
      H - 30,
      { width: colW },
    );
  doc.end();
}
